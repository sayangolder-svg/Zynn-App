const fs = require("fs");
const path = require("path");

function parseEnv(content) {
  const result = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) {
      continue;
    }
    const idx = line.indexOf("=");
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    result[key] = value;
  }
  return result;
}

function toEnvLines(envObj) {
  const lines = [
    "# AUTO-GENERATED from ../.env by scripts/sync-shared-env.js",
    "# Do not edit this file directly. Edit the root .env instead.",
    "",
  ];

  for (const [key, value] of Object.entries(envObj)) {
    lines.push(`${key}=${value}`);
  }

  lines.push("");
  return lines.join("\n");
}

function main() {
  const appDir = path.resolve(__dirname, "..");
  const rootEnvPath = path.resolve(appDir, "..", ".env");
  const appEnvPath = path.resolve(appDir, ".env");

  if (!fs.existsSync(rootEnvPath)) {
    console.log("[sync-shared-env] Root .env not found. Skipping sync.");
    process.exit(0);
  }

  const rootEnv = parseEnv(fs.readFileSync(rootEnvPath, "utf8"));

  const host = rootEnv.APP_HOST || "127.0.0.1";
  const djangoPort = rootEnv.DJANGO_PORT || "8000";
  const backendBase =
    rootEnv.BACKEND_BASE_URL || `http://${host}:${djangoPort}`;

  const publicEnv = {};

  for (const [key, value] of Object.entries(rootEnv)) {
    if (key.startsWith("EXPO_PUBLIC_")) {
      publicEnv[key] = value;
    }
  }

  if (!publicEnv.EXPO_PUBLIC_BACKEND_BASE_URL) {
    publicEnv.EXPO_PUBLIC_BACKEND_BASE_URL = backendBase;
  }

  if (!publicEnv.EXPO_PUBLIC_API_BASE_URL) {
    publicEnv.EXPO_PUBLIC_API_BASE_URL = `${backendBase.replace(/\/$/, "")}/api`;
  }

  fs.writeFileSync(appEnvPath, toEnvLines(publicEnv), "utf8");
  console.log(`[sync-shared-env] Synced ${Object.keys(publicEnv).length} vars to Zynn-App/.env`);
}

main();
